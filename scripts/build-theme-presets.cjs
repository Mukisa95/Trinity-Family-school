/* One palette definition generates CSS roles and Tailwind's preset-aware families. */
const fs = require('node:fs');
const path = require('node:path');
const colours = require('tailwindcss/colors');
const root = path.resolve(__dirname, '..');
const shades = [50,100,200,300,400,500,600,700,800,900,950];
const families = { brand: 'blue', 'brand-alt': 'indigo', 'brand-secondary': 'purple', 'brand-secondary-alt': 'violet' };
const presets = {
  'trinity-classic': { brand:'blue', 'brand-alt':'indigo', 'brand-secondary':'purple', 'brand-secondary-alt':'violet' },
  'soft-indigo': { brand:'indigo', 'brand-alt':{indigo:.75,violet:.25}, 'brand-secondary':'violet', 'brand-secondary-alt':{violet:.8,indigo:.2} },
};
const rgb = hex => [1,3,5].map(i=>parseInt(hex.slice(i,i+2),16)).join(' ');
function tone(hue, shade) {
  if (typeof hue === 'string') return rgb(colours[hue][shade]);
  return [0,1,2].map(i=>Math.round(Object.entries(hue).reduce((sum,[name,weight])=>sum+Number(rgb(colours[name][shade]).split(' ')[i])*weight,0))).join(' ');
}
function palette(preset) {
  return Object.entries(presets[preset]).flatMap(([family,hue])=>shades.map(shade=>`  --${family}-${shade}: ${tone(hue,shade)};`)).join('\n');
}
function ink(dark) {
  return Object.keys(families).flatMap(family=>shades.map(shade=>{
    const readable = dark ? (shade>=900?100:shade>=700?200:shade>=500?300:shade) : shade;
    return `  --${family}-ink-${shade}: var(--${family}-${readable});`;
  })).join('\n');
}
function surfaces(preset, dark = false) {
  return Object.entries(presets[preset]).flatMap(([family,hue])=>shades.map(shade=>{
    if (dark && (shade === 400 || shade === 500)) return `  --${family}-surface-${shade}: var(--${family}-600);`;
    if (!dark || shade > 200) return `  --${family}-surface-${shade}: var(--${family}-${shade});`;
    const weight = shade === 50 ? .16 : shade === 100 ? .23 : .32;
    const base = preset === 'soft-indigo' ? [15,19,31] : [15,23,42];
    const accent = tone(hue,500).split(' ').map(Number);
    const mixed = base.map((n,i)=>Math.round(n*(1-weight)+accent[i]*weight)).join(' ');
    return `  --${family}-surface-${shade}: ${mixed};`;
  })).join('\n');
}
// Solid navigation tones are deliberately more colourful than neutral cards.
function navigationRoles(preset, dark = false) {
  const hue = preset === 'soft-indigo' ? {indigo:.65,violet:.35} : 'blue';
  const blend = (base, accent, weight) => base.map((n,i)=>Math.round(n*(1-weight)+accent[i]*weight)).join(' ');
  const base = dark ? (preset === 'soft-indigo' ? [15,19,31] : [15,23,42]) : [255,255,255];
  const accent = tone(hue,dark?400:500).split(' ').map(Number);
  return `  --navigation-surface: ${blend(base,accent,dark?.22:.24)};
  --navigation-control: ${blend(base,accent,dark?.14:.10)};
  --navigation-border: ${blend(base,accent,dark?.36:.34)};`;
}
// Small class/subject labels need their own paired colours, not translucent button fills.
function lessonRoles(dark) {
  return ['green','indigo','amber','pink','teal','violet','orange','cyan'].flatMap(hue=>{
    const value = shade => hue==='indigo' ? `var(--brand-alt-${shade})` : hue==='violet' ? `var(--brand-secondary-alt-${shade})` : rgb(colours[hue][shade]);
    return [
      `  --lesson-${hue}-ink: ${value(dark?300:700)};`,
      `  --lesson-${hue}-surface: ${value(dark?950:50)};`,
      `  --lesson-${hue}-hover: ${value(dark?900:100)};`,
      `  --lesson-${hue}-border: ${value(dark?700:300)};`,
      `  --lesson-${hue}-header: ${value(dark?900:700)};`,
      `  --lesson-${hue}-header-ink: ${dark?value(200):'255 255 255'};`,
    ];
  }).join('\n');
}
const classic = palette('trinity-classic');
const neutralPaperReset = ['slate','gray','zinc','neutral','stone'].flatMap(family=>shades.map(shade=>`  --ui-neutral-${family}-${shade}: initial;`)).join('\n');
const css = `/* Generated by scripts/build-theme-presets.cjs. Text and fills have separate roles. */
:root, [data-app-theme="trinity-classic"] {\n${classic}\n${ink(false)}\n${surfaces('trinity-classic')}\n${navigationRoles('trinity-classic')}\n}
[data-app-theme="soft-indigo"] {\n${palette('soft-indigo')}\n${ink(false)}\n${surfaces('soft-indigo')}\n${navigationRoles('soft-indigo')}\n}
.dark, .dark [data-app-theme] {\n${ink(true)}\n}
.dark, .dark [data-app-theme="trinity-classic"] {\n${surfaces('trinity-classic',true)}\n${navigationRoles('trinity-classic',true)}\n}
.dark[data-app-theme="soft-indigo"], .dark [data-app-theme="soft-indigo"] {\n${surfaces('soft-indigo',true)}\n${navigationRoles('soft-indigo',true)}\n}
:root, [data-app-theme] {
${lessonRoles(false)}
  --primary: 221.2 83.2% 53.3%; --primary-foreground: 0 0% 100%;
  --ring: var(--primary);
  --link: var(--brand-ink-600); --link-hover: var(--brand-ink-800);
  --brand-fill: var(--brand-600); --brand-fill-hover: var(--brand-700);
  --brand-on-fill: 255 255 255;
  --sidebar-primary: var(--primary); --sidebar-primary-foreground: var(--primary-foreground);
  --sidebar-ring: var(--ring);
  --calendar-today: rgb(var(--brand-500));
  --dashboard-tracker-border: rgb(var(--brand-alt-200));
}
[data-app-theme="soft-indigo"] { --primary: 243.4 75.4% 58.6%; }
.dark { --ring: 213 94% 68%; --sidebar-ring: var(--ring); --calendar-today: rgb(var(--brand-600)); --dashboard-tracker-border: rgb(var(--brand-alt-800)); }
.dark, .dark [data-app-theme] {\n${lessonRoles(true)}\n}
.dark[data-app-theme="soft-indigo"], .dark [data-app-theme="soft-indigo"] {
  --background: 228 35% 9%; --card: 225 30% 16%; --popover: 225 28% 20%;
  --glass-surface: 15 19 31; --glass-edge: 112 119 148;
  --accent: 230 28% 21%; --border: 225 22% 27%; --input: var(--border); --ring: 234 89% 85%;
  --sidebar-background: 228 32% 12%; --sidebar-accent: 230 28% 21%; --sidebar-border: var(--border);
}
.dark, .dark [data-app-theme] { --calendar-control: rgb(var(--brand-alt-ink-700)); }
/* Paper uses the original Classic palette, independently of the selected screen preset. */
[data-theme-surface="paper"], [data-theme-surface="paper-error"], [data-theme-surface="paper-overlay"] {\n${classic}\n${ink(false)}\n${surfaces('trinity-classic')}\n${lessonRoles(false)}\n${neutralPaperReset}\n  --primary: 221.2 83.2% 53.3%; --primary-foreground: 0 0% 100%;
}
@media print {
  :root, :root.dark[data-app-theme], .dark [data-app-theme], [data-app-theme] {\n${classic}\n${ink(false)}\n${surfaces('trinity-classic')}\n${lessonRoles(false)}\n    --primary: 221.2 83.2% 53.3%; --primary-foreground: 0 0% 100%;
    --background: 0 0% 100%; --foreground: 222 47% 11%;
    --card: 0 0% 100%; --card-foreground: 222 47% 11%; --popover: 0 0% 100%;
    --accent: 210 40% 96%; --border: 214 32% 91%; --input: 214 32% 91%;
    --sidebar-background: 210 40% 98%; --sidebar-accent: 214 32% 94%; --sidebar-border: 214 32% 91%;
    --calendar-today: rgb(var(--brand-500)); --dashboard-tracker-border: rgb(var(--brand-alt-200));
  }
}
`;
fs.writeFileSync(path.join(root,'src/app/brand-theme.css'),css);
const counts = Object.keys(presets).length;
console.log(`THEME_PRESETS_BUILT ${counts} presets, ${Object.keys(families).length} accent families; independent text/fill and paper roles.`);
